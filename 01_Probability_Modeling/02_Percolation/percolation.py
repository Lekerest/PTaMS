# УСЛОВИЕ ЗАДАЧИ: вычисление вероятности перколяции.
# 1. Генерировать прямоугольное поле из одинаковых квадратных клеток.
#    Каждая клетка проходима с вероятностью p независимо от остальных.
# 2. Проверять, есть ли путь от любой проходимой клетки верхнего ряда
#    до любой проходимой клетки нижнего ряда. Переходить можно только
#    по проходимым клеткам с общей стороной, без переходов по диагонали.
# 3. Для каждого p провести много опытов, каждый раз создавая новое поле.
#    Вероятность перколяции оценить долей полей, в которых найден путь.
# 4. Построить график вероятности перколяции в зависимости от p.
# 5. Размеры поля, набор p и число опытов выбрать самостоятельно.
#    Размеры поля должны оставаться одинаковыми для всех точек графика.
# 6. Задать seed один раз до генерации случайных чисел.

import random  # Нужен для случайного выбора проходимости каждой клетки.
from collections import deque  # Очередь для обхода клеток в порядке их обнаружения.
import matplotlib.pyplot as plt  # Нужен для построения графика вероятности.

# Параметры эксперимента
ROWS = 30  # Число строк поля; не меняется между опытами.
COLS = 30  # Число столбцов поля; не меняется между опытами.
TRIALS = 1000  # Сколько новых полей генерируем для каждого значения p.
P_VALUES = [  # Вероятности проходимости клеток, для которых проводим эксперименты.
    0, 0.1, 0.2, 0.3, 0.4, 0.45, 0.5, 0.525, 0.55, 0.575,
    0.6, 0.625, 0.65, 0.675, 0.7, 0.75, 0.8, 0.9, 1,
]
random.seed(42)  # Фиксируем генератор один раз для повторяемости всей серии опытов.


# Проверка существования пути сверху вниз
def has_path(field):  # Получает поле: True — проходимая клетка, False — непроходимая.
    # Строки и столбцы нумеруются с нуля, поэтому верхний ряд имеет индекс 0.
    # Добавляем все открытые клетки верхнего ряда: путь может начинаться в любой из них.
    queue = deque((0, col) for col in range(COLS) if field[0][col])
    visited = set(queue)  # Запоминаем обнаруженные клетки, чтобы не обходить их повторно.

    while queue:  # Продолжаем обход, пока есть клетки, соседей которых ещё нужно проверить.
        row, col = queue.popleft()  # Берём самую раннюю добавленную клетку из начала очереди.
        if row == ROWS - 1:  # Последний ряд имеет индекс ROWS - 1: мы дошли до низа.
            return True  # Найден хотя бы один путь, поэтому дальнейший обход не нужен.

        # dr меняет строку, dc — столбец. Эти четыре пары задают только соседей по стороне.
        for dr, dc in [(1, 0), (-1, 0), (0, 1), (0, -1)]:  # Вниз, вверх, вправо, влево.
            nr, nc = row + dr, col + dc  # Вычисляем координаты очередного соседа.
            if 0 <= nr < ROWS and 0 <= nc < COLS:  # Проверяем, что сосед находится внутри поля.
                if field[nr][nc] and (nr, nc) not in visited:  # Клетка открыта и ещё не обнаружена.
                    visited.add((nr, nc))  # Сразу отмечаем её, чтобы не добавить в очередь дважды.
                    queue.append((nr, nc))  # Ставим в конец очереди для дальнейшего обхода.

    return False  # Все достижимые клетки проверены, но нижний ряд не достигнут: пути нет.


# Моделирование для каждого значения p
probabilities = []  # Оценки вероятности перколяции для точек будущего графика.

for p in P_VALUES:  # По очереди рассматриваем каждую вероятность проходимости клетки.
    successes = 0  # Начинаем подсчёт успешных полей заново для текущего p.
    for _ in range(TRIALS):  # Повторяем опыт TRIALS раз; номер опыта не нужен, поэтому используем _.
        # random.random() равномерно выбирает число от 0 включительно до 1 не включительно.
        # Сравнение с p даёт True с вероятностью p. Для каждой клетки делаем отдельный вызов.
        field = [  # Создаём новое поле для этого опыта как список строк.
            [random.random() < p for _ in range(COLS)]  # Одна строка из COLS независимых клеток.
            for _ in range(ROWS)  # Повторяем создание строки ROWS раз.
        ]
        if has_path(field):  # Проверяем, соединены ли верхний и нижний ряды поля.
            successes += 1  # Если путь существует, учитываем один успешный опыт.

    probability = successes / TRIALS  # Доля успешных опытов — оценка вероятности перколяции.
    probabilities.append(probability)  # Сохраняем оценку в том же порядке, что и значения p.
    print(f"p = {p:.3f}: {successes}/{TRIALS}, вероятность = {probability:.3f}")  # Выводим итог для p.

# График вероятности перколяции
plt.plot(P_VALUES, probabilities, marker="o")  # По X — p, по Y — оценки; каждый кружок — итог серии для p.
plt.xlabel("Вероятность проходимости клетки p")  # Подписываем горизонтальную ось.
plt.ylabel("Вероятность перколяции")  # Подписываем вертикальную ось.
plt.title(f"Перколяция: поле {ROWS} × {COLS}, опытов на p: {TRIALS}")  # Указываем параметры эксперимента.
plt.grid()  # Включаем сетку для удобного чтения значений.
plt.tight_layout()  # Размещаем подписи так, чтобы они помещались в окне.
plt.show()  # Открываем окно с готовым графиком.
