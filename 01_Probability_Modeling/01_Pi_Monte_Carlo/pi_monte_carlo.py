# УСЛОВИЕ ЗАДАЧИ: вычисление числа π методом Монте-Карло.
# Источник: lectures.pdf, страницы 36–38.
# 1. Равномерно генерировать точки внутри квадрата, независимо выбирая x и y.
# 2. Проверять попадание каждой точки в круг, вписанный в этот квадрат.
# 3. По доле попаданий приближённо вычислить число π.
# 4. Построить график абсолютной ошибки abs(оценка π - math.pi)
#    в зависимости от количества использованных точек.
#    Можно пересчитывать оценку после каждой новой точки.
# 5. Задать seed один раз до генерации, чтобы опыт можно было повторить.
# Число точек выбираем самостоятельно. Ошибка может увеличиваться
# на отдельных шагах — она не обязана убывать после каждой точки.

import math  # Содержит math.pi — значение π для вычисления ошибки.
import random  # Генерирует псевдослучайные координаты точек.
import matplotlib.pyplot as plt  # Нужен для построения графика ошибки.

# Параметры эксперимента
N = 100000  # Общее количество точек, которые будем бросать в квадрат.
random.seed(42)  # Один раз фиксируем генератор: при новом запуске точки повторятся.

# Генерация точек и вычисление числа pi
hits = 0  # Счётчик точек, попавших внутрь круга или на его границу.
errors = []  # Сюда записываем ошибку после каждой точки для будущего графика.

for n in range(1, N + 1):  # n — число уже сгенерированных точек; верхняя граница range не включается.
    x = random.uniform(0, 1)  # Равномерно выбираем координату по горизонтали.
    y = random.uniform(0, 1)  # Отдельным вызовом выбираем независимую координату по вертикали.

    # Круг вписан в квадрат 1 × 1: его центр (0.5, 0.5), радиус 0.5.
    # Слева — квадрат расстояния до центра, справа — квадрат радиуса.
    if (x - 0.5) ** 2 + (y - 0.5) ** 2 <= 0.25:  # Проверяем, попала ли точка в круг.
        hits += 1  # При попадании увеличиваем общий счётчик на единицу.

    pi_estimate = 4 * hits / n
    # Площадь круга радиуса 0.5 равна π/4, а площадь квадрата равна 1.
    # Поэтому доля попаданий hits/n приближает π/4, и для оценки π умножаем на 4.
    errors.append(abs(pi_estimate - math.pi))  # Модуль разности даёт абсолютную ошибку.

# Результат
print(f"Количество точек: {N}")  # Показываем объём проведённого эксперимента.
print(f"Попаданий в круг: {hits}")  # Показываем число успешных попаданий.
print(f"Оценка pi: {pi_estimate:.8f}")  # Выводим итоговую оценку с 8 знаками после точки.
print(f"Абсолютная ошибка: {errors[-1]:.8f}")  # Индекс -1 берёт последнюю, итоговую ошибку.

# График абсолютной ошибки
plt.plot(range(1, N + 1), errors)  # По X — число точек, по Y — соответствующая ошибка.
plt.xlabel("Количество точек")  # Подписываем горизонтальную ось.
plt.ylabel("Абсолютная ошибка")  # Подписываем вертикальную ось.
plt.title("Ошибка оценки числа π методом Монте-Карло")  # Задаём название графика.
plt.grid()  # Включаем сетку, чтобы удобнее сравнивать значения.
plt.tight_layout()  # Размещаем подписи так, чтобы они помещались в окне.
plt.show()  # Открываем окно с готовым графиком.
