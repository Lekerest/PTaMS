# УСЛОВИЕ ЗАДАЧИ: практическое задание 3. Бутстрэп.
# По одной выборке независимых одинаково распределённых наблюдений:
# 1. Оценить приближённый 95%-й доверительный интервал для MAD:
#    MAD = median(|Xi - median(X)|).
# 2. Методом бутстрэпа оценить приближённый 95%-й доверительный
#    интервал для выборочной дисперсии по той же исходной выборке.
# 3. Сравнить интервалы и сделать выводы. Учесть, что MAD измеряется
#    в единицах данных, а дисперсия — в квадрате этих единиц,
#    поэтому напрямую сравнивать ширины интервалов нельзя.
# Используем перцентильный бутстрэп: границы — процентили 2.5 и 97.5.

import numpy as np  # Вычисления с выборками, медианы, дисперсии и процентили.

####################################################
# 1 Исходная выборка и параметры
####################################################

np.random.seed(42)
X = np.random.exponential(scale=1.0, size=10000)  # Выборка как в условии
B = 10000  # Число повторных выборок по которым строим интервалы

####################################################
# 2 Статистики исходной выборки
####################################################
median = np.median(X)  # Находим общую медиану исходных наблюдений
mad = np.median(np.abs(X - median))  # Медиана абсолютных отклонений от медианы
variance = np.var(X, ddof=0)  # Выборочная дисперсия: сумма квадратов отклонений / n.

####################################################
# 3 Бутстрап
####################################################
mad_values = []  # Значения MAD, полученные на повторных выборках.
variance_values = []  # Значения дисперсии на тех же повторных выборках.

for _ in range(B):  # Повторяем процедуру B раз.
    sample = np.random.choice(X, size=len(X), replace=True)  # Берём n значений с возвращением.
    sample_median = np.median(sample)  # Для каждой новой выборки пересчитываем её медиану.
    mad_values.append(np.median(np.abs(sample - sample_median)))  # Считаем и сохраняем её MAD.
    variance_values.append(np.var(sample, ddof=0))  # Считаем и сохраняем её дисперсию.

####################################################
# 4 Перцентильные 95%-е доверительные интервалы
####################################################
mad_interval = np.percentile(mad_values, [2.5, 97.5])  # Нижняя и верхняя границы для MAD.
variance_interval = np.percentile(variance_values, [2.5, 97.5])  # Границы для дисперсии.

print(f"Размер исходной выборки: {len(X)}, бутстрэп-выборок: {B}")
print(f"MAD исходной выборки: {mad:.6f}")  # Выводим исходную оценку разброса через медиану.
print(f"95%-й интервал для MAD: [{mad_interval[0]:.6f}; {mad_interval[1]:.6f}]")
print(f"Выборочная дисперсия: {variance:.6f}")  # Выводим исходную оценку дисперсии.
print(f"95%-й интервал для дисперсии: [{variance_interval[0]:.6f}; {variance_interval[1]:.6f}]")

####################################################
# 5 Сравнение
####################################################

# Получаем безразмерные относительные ширины, которые можно сопоставлять.
mad_relative_width = (mad_interval[1] - mad_interval[0]) / mad
variance_relative_width = (variance_interval[1] - variance_interval[0]) / variance
print(f"Относительная ширина интервала MAD: {mad_relative_width:.2%}")  # .2% выводит проценты.
print(f"Относительная ширина интервала дисперсии: {variance_relative_width:.2%}")
